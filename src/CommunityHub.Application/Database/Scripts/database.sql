CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL,
    birthday DATE NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('Manager', 'Citizen', 'Tenant', 'Cordinator'))
);

CREATE TABLE posts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE countries (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE cities (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    postalCode TEXT NOT NULL,
    country_id BIGINT NOT NULL,
    FOREIGN KEY (country_id) REFERENCES countries(id)
);

CREATE TABLE buildings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    address VARCHAR(255) NOT NULL,
    settlement VARCHAR(150) NOT NULL,
    city VARCHAR(120) NOT NULL,
    country VARCHAR(120) NOT NULL,
    floor_number INT NOT NULL CHECK (floor_number > 0),
    manager_id BIGINT NOT NULL,
    FOREIGN KEY (manager_id) REFERENCES users(id)
);

CREATE TABLE flats (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL,
    floor_number INT NOT NULL CHECK (floor_number > 0),
    flat_number INT NOT NULL CHECK (flat_number > 0),
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE
);

CREATE TABLE building_pictures (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL,
    picture_path TEXT NOT NULL,
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE
);

CREATE TABLE building_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    building_id BIGINT NOT NULL,
    flat_number INT NOT NULL CHECK (flat_number > 0),
    created_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('Pending', 'Accepted', 'Denied')),
    rejection_explanation TEXT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE
);

CREATE TABLE building_memberships (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    floor_number INT NOT NULL CHECK (floor_number > 0),
    flat_number INT NOT NULL CHECK (flat_number > 0),
    joined_at TIMESTAMP NOT NULL,
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id),
    UNIQUE (building_id, user_id),
    UNIQUE (building_id, flat_number)
);

CREATE TABLE neighborhoods (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    coordinator_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    budget DECIMAL(15,2) NOT NULL DEFAULT 0,
    city_id BIGINT NOT NULL,
    images TEXT[] NOT NULL DEFAULT '{}',
    FOREIGN KEY (coordinator_id) REFERENCES users(id),
    FOREIGN KEY (city_id) REFERENCES cities(id)
);

CREATE TABLE streets (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    start_number INT NOT NULL,
    end_number INT NOT NULL,
    neighborhood_id BIGINT NOT NULL,
    FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods(id)
);

CREATE TABLE neighborhood_membership_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    neighborhood_id BIGINT NOT NULL,
    citizen_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    rejection_reason TEXT NULL,
    FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods(id) ON DELETE CASCADE,
    FOREIGN KEY (citizen_id) REFERENCES users(id)
);

CREATE TABLE neighborhood_memberships (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    neighborhood_id BIGINT NOT NULL,
    citizen_id BIGINT NOT NULL,
    joined_at TIMESTAMP NOT NULL,
    FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods(id) ON DELETE CASCADE,
    FOREIGN KEY (citizen_id) REFERENCES users(id),
    UNIQUE (neighborhood_id, citizen_id)
);

CREATE TABLE citizens (
    user_id BIGINT PRIMARY KEY,
    address VARCHAR(255) NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE common_spaces (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    floor_number INT NOT NULL,
    rental_type VARCHAR(20) NOT NULL CHECK (rental_type IN ('SingleDay', 'MultipleDays')),
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE
);

CREATE TABLE common_space_rental_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    common_space_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    requested_start_date DATE NOT NULL,
    requested_end_date DATE NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('Pending', 'PendingChangeOfDate', 'Approved', 'Rejected')),
    approved_date DATE NULL,
    FOREIGN KEY (common_space_id) REFERENCES common_spaces(id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id) REFERENCES users(id)
);

CREATE TABLE meetings (
    id BIGSERIAL PRIMARY KEY,
    neighborhood_id BIGINT NOT NULL REFERENCES neighborhoods(id),
    topic VARCHAR(50) NOT NULL,
    time TIME NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'InPreparation',
    scheduled_date DATE NULL
);

CREATE TABLE meeting_date_votes (
    id BIGSERIAL PRIMARY KEY,
    meeting_id BIGINT NOT NULL REFERENCES meetings(id),
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    voted_date DATE NOT NULL,
    UNIQUE(meeting_id, citizen_id)
);


CREATE TABLE forums (
    id BIGSERIAL PRIMARY KEY,
    coordinator_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE forum_comments (
    id BIGSERIAL PRIMARY KEY,
    forum_id BIGINT NOT NULL REFERENCES forums(id) ON DELETE CASCADE,
    coordinator_id BIGINT NOT NULL REFERENCES users(id),
    neighborhood_name VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE forum_reactions (
    id BIGSERIAL PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES forum_comments(id) ON DELETE CASCADE,
    coordinator_id BIGINT NOT NULL REFERENCES users(id),
    is_positive BOOLEAN NOT NULL,
    UNIQUE(comment_id, coordinator_id)
);

CREATE TABLE help_ads (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    building_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    description TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    category VARCHAR(100) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE help_ad_slots (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    help_ad_id BIGINT NOT NULL,
    slot_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    FOREIGN KEY (help_ad_id) REFERENCES help_ads(id) ON DELETE CASCADE
);

CREATE TABLE events (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    neighborhood_id BIGINT NOT NULL,
    organizer_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
    min_volunteers INT NOT NULL CHECK (min_volunteers > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('Preparation', 'Scheduled', 'Cancelled', 'Finished')),
    FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods(id),
    FOREIGN KEY (organizer_id) REFERENCES users(id)
);

CREATE TABLE event_items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
);

CREATE TABLE event_volunteers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    citizen_id BIGINT NOT NULL,
    attended BOOLEAN NULL,
    FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    FOREIGN KEY (citizen_id) REFERENCES users(id),
    UNIQUE (event_id, citizen_id)
);

CREATE TABLE event_volunteer_items (
    volunteer_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    PRIMARY KEY (volunteer_id, item_id),
    FOREIGN KEY (volunteer_id) REFERENCES event_volunteers(id) ON DELETE CASCADE,
    FOREIGN KEY (item_id) REFERENCES event_items(id) ON DELETE CASCADE
);


-- 3.5 Gradski objekti i rezervacije
CREATE TABLE city_objects (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    vote_count INT NOT NULL DEFAULT 0,
    last_visit_date DATE NULL
);

CREATE TABLE city_object_reservations (
    id BIGSERIAL PRIMARY KEY,
    city_object_id BIGINT NOT NULL REFERENCES city_objects(id),
    neighborhood_id BIGINT NOT NULL REFERENCES neighborhoods(id),
    start_datetime TIMESTAMP NOT NULL,
    end_datetime TIMESTAMP NOT NULL,
    duration_minutes INT NOT NULL
);

CREATE TABLE city_object_votes (
    id BIGSERIAL PRIMARY KEY,
    city_object_id BIGINT NOT NULL REFERENCES city_objects(id),
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    UNIQUE(city_object_id, citizen_id)
);

-- 3.6 Recenzije koordinatora
CREATE TABLE coordinator_reviews (
    id BIGSERIAL PRIMARY KEY,
    coordinator_id BIGINT NOT NULL REFERENCES users(id),
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    rating INT NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    is_removed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE coordinator_review_reports (
    id BIGSERIAL PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES coordinator_reviews(id),
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    UNIQUE(review_id, citizen_id)
);

-- 3.7 Budžet - kategorije, donacije i troškovi
CREATE TABLE budget_categories (
    id BIGSERIAL PRIMARY KEY,
    neighborhood_id BIGINT NOT NULL REFERENCES neighborhoods(id),
    name VARCHAR(200) NOT NULL,
    total_amount DECIMAL(15,2) NOT NULL DEFAULT 0
);

CREATE TABLE donations (
    id BIGSERIAL PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES budget_categories(id),
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    amount DECIMAL(15,2) NOT NULL,
    donated_at TIMESTAMP NOT NULL
);

CREATE TABLE expenses (
    id BIGSERIAL PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES budget_categories(id),
    amount DECIMAL(15,2) NOT NULL,
    description TEXT NOT NULL,
    expense_date DATE NOT NULL
);

-- 3.8 Poklon grada
CREATE TABLE city_gifts (
    id BIGSERIAL PRIMARY KEY,
    amount DECIMAL(15,2) NOT NULL,
    deadline DATE NOT NULL,
    is_assigned BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE city_gift_applications (
    id BIGSERIAL PRIMARY KEY,
    city_gift_id BIGINT NOT NULL REFERENCES city_gifts(id),
    neighborhood_id BIGINT NOT NULL REFERENCES neighborhoods(id),
    UNIQUE(city_gift_id, neighborhood_id)
);